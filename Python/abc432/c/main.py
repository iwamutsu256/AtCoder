# 小さな飴の重量はXグラム 大きな飴の重量はYグラム
# 子供の数はN人
# 小さな飴の個数をBi 大きな飴の個数をCiとすると、
# Ai = Bi + Ci
# BiX + CiY = BjX + CjY
# Bi = Ai - Ci
# (Ai - Ci)X + CiY = (Aj - Cj)X + CjY
# AiX - CiX + CiY = AjX - CjX + CjY
# AiX - AjX = CiX - CiY - CjX + CjY
# (Ai-Aj)X = (Ci-Cj)X - (Ci-Cj)Y = (Ci-Cj)(X-Y)
# (Ai-Aj)/(Ci-Cj) = (X-Y)/X